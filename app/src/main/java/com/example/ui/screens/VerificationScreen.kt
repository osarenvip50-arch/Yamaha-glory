package com.example.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.data.model.VerificationReport
import com.example.ui.components.StatusBadge
import com.example.ui.theme.*

@Composable
fun VerificationScreen(
    verifications: List<VerificationReport>,
    onTriggerVerification: (String, String) -> Unit
) {
    var showDialog by remember { mutableStateOf(false) }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        // Header
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Column {
                Text(
                    text = "INDEPENDENT VERIFICATION SERVICE",
                    style = MaterialTheme.typography.titleLarge,
                    color = TextPrimary,
                    fontWeight = FontWeight.Bold
                )
                Text(
                    text = "Rigorous multi-layer verification • Acceptance criteria • Test harnesses • Error correction",
                    style = MaterialTheme.typography.labelSmall,
                    color = TextSecondary
                )
            }

            Button(
                onClick = { showDialog = true },
                colors = ButtonDefaults.buttonColors(containerColor = CyanPrimary, contentColor = DarkNavyBase),
                modifier = Modifier.testTag("verify_new_action")
            ) {
                Icon(Icons.Default.FactCheck, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(modifier = Modifier.width(4.dp))
                Text("Verify Output", style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.Bold)
            }
        }

        Spacer(modifier = Modifier.height(14.dp))

        // Architectural Verification Standard Card
        Card(
            colors = CardDefaults.cardColors(containerColor = DarkNavyCard),
            shape = RoundedCornerShape(12.dp),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(DarkNavyBorder))
        ) {
            Column(modifier = Modifier.padding(14.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(Icons.Default.VerifiedUser, contentDescription = null, tint = AccentGreen, modifier = Modifier.size(20.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "ZERO-SIMULATION VERIFICATION POLICY",
                        style = MaterialTheme.typography.labelSmall,
                        color = AccentGreen,
                        fontWeight = FontWeight.Bold
                    )
                }
                Spacer(modifier = Modifier.height(6.dp))
                Text(
                    text = "Outputs generated by Friday or OOX1 models are NEVER self-evaluated by asking the same model. The Independent Verification Service executes isolated unit tests, validates facts against external ground truths, checks numerical calculations, and inspects media artifacts for defects.",
                    style = MaterialTheme.typography.bodySmall,
                    color = TextSecondary
                )
            }
        }

        Spacer(modifier = Modifier.height(14.dp))

        // Reports List
        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            items(verifications) { report ->
                Card(
                    colors = CardDefaults.cardColors(containerColor = DarkNavyCard),
                    shape = RoundedCornerShape(12.dp),
                    border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(DarkNavyBorder))
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Column(modifier = Modifier.weight(1f)) {
                                Text(
                                    text = "Target: ${report.targetType}",
                                    style = MaterialTheme.typography.titleMedium,
                                    color = TextPrimary,
                                    fontWeight = FontWeight.Bold
                                )
                                Text(
                                    text = "Request: ${report.originalRequest}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = TextSecondary
                                )
                            }

                            StatusBadge(
                                text = report.verificationStatus,
                                color = when (report.verificationStatus) {
                                    "VERIFIED_PASSED" -> AccentGreen
                                    "VERIFIED_CORRECTED" -> AccentAmber
                                    else -> AccentRed
                                }
                            )
                        }

                        Spacer(modifier = Modifier.height(10.dp))

                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .clip(RoundedCornerShape(8.dp))
                                .background(DarkNavyBase)
                                .padding(10.dp)
                        ) {
                            Column {
                                Text(
                                    text = "ACCEPTANCE CRITERIA: ${report.acceptanceCriteria}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = CyanGlow
                                )
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = "INDEPENDENT TESTS PERFORMED: ${report.independentTestsRun}",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = TextPrimary
                                )
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = "DETECTED DEFECTS: ${report.detectedErrors}",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = if (report.detectedErrors == "None") AccentGreen else AccentRed
                                )
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = "CORRECTIONS: ${report.correctionsApplied}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = TextSecondary
                                )
                            }
                        }

                        Spacer(modifier = Modifier.height(8.dp))
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween
                        ) {
                            Text(
                                text = "Remaining Uncertainties: ${report.remainingUncertainties}",
                                style = MaterialTheme.typography.labelSmall,
                                color = TextMuted
                            )
                            Text(
                                text = "Score: ${(report.confidenceScore * 100).toInt()}%",
                                style = MaterialTheme.typography.labelSmall,
                                color = AccentGreen,
                                fontWeight = FontWeight.Bold
                            )
                        }
                    }
                }
            }
        }
    }

    if (showDialog) {
        var req by remember { mutableStateOf("") }
        var target by remember { mutableStateOf("Code Execution") }

        AlertDialog(
            onDismissRequest = { showDialog = false },
            title = { Text("Request Independent Output Verification", style = MaterialTheme.typography.titleMedium, color = TextPrimary) },
            text = {
                Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedTextField(
                        value = req,
                        onValueChange = { req = it },
                        label = { Text("Original User Requirement / Output") },
                        modifier = Modifier.fillMaxWidth()
                    )
                    Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        FilterChip(selected = target == "Code Execution", onClick = { target = "Code Execution" }, label = { Text("Code") })
                        FilterChip(selected = target == "Factual Claim", onClick = { target = "Factual Claim" }, label = { Text("Facts") })
                        FilterChip(selected = target == "Video/Audio Artifact", onClick = { target = "Video/Audio Artifact" }, label = { Text("Media") })
                    }
                }
            },
            confirmButton = {
                Button(
                    onClick = {
                        if (req.isNotBlank()) {
                            onTriggerVerification(req, target)
                            showDialog = false
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = CyanPrimary, contentColor = DarkNavyBase)
                ) {
                    Text("Execute Audit")
                }
            },
            dismissButton = {
                TextButton(onClick = { showDialog = false }) {
                    Text("Cancel", color = TextSecondary)
                }
            },
            containerColor = DarkNavyCard
        )
    }
}
